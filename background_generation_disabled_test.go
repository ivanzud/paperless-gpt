package main

import (
	"context"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

// With every AUTO_GENERATE_* switch off, a document that gets AUTO_TAG must
// come out with its metadata untouched: no model is asked for anything (the
// app has none here, so a call would fail) and the only thing written is the
// tag handover. This is what lets another tool own the metadata while
// paperless-gpt only does OCR.
func TestProcessAutoTagDocuments_AllGenerationDisabledLeavesMetadataAlone(t *testing.T) {
	prevAutoTag, prevAutoOcrTag, prevComplete := autoTag, autoOcrTag, autoTagComplete
	prevTitle, prevTags, prevCorr, prevDate, prevType := autoGenerateTitle, autoGenerateTags, autoGenerateCorrespondents, autoGenerateCreatedDate, autoGenerateDocumentType
	t.Cleanup(func() {
		autoTag, autoOcrTag, autoTagComplete = prevAutoTag, prevAutoOcrTag, prevComplete
		autoGenerateTitle, autoGenerateTags, autoGenerateCorrespondents, autoGenerateCreatedDate, autoGenerateDocumentType = prevTitle, prevTags, prevCorr, prevDate, prevType
	})
	autoTag, autoOcrTag, autoTagComplete = "paperless-gpt-auto", "paperless-gpt-ocr-auto", "paperless-gpt-auto-complete"
	autoGenerateTitle, autoGenerateTags, autoGenerateCorrespondents, autoGenerateCreatedDate, autoGenerateDocumentType = "false", "false", "false", "false", "false"

	env := setupTest(t)
	defer env.teardown()

	client := &mockClientWithCapture{mockClient: newMockClient(env.client)}
	doc := Document{
		ID:               5,
		Title:            "Statement 1234",
		Content:          "Example Bank statement for Jane Doe",
		Correspondent:    "Example Bank",
		DocumentTypeName: "Statement",
		CreatedDate:      "2020-01-02",
		Tags:             []string{autoTag, "finance"},
	}
	client.AddDocument(doc, []string{autoTag})

	app := &App{Client: client, Database: env.db} // no LLM configured
	count, err := app.processAutoTagDocuments(context.Background())
	require.NoError(t, err)
	assert.Equal(t, 1, count)

	require.True(t, client.updateDocsCalled, "the trigger tag still has to come off")
	require.Len(t, client.lastSuggestions, 1)
	got := client.lastSuggestions[0]
	assert.Equal(t, doc.Title, got.SuggestedTitle, "the title is passed through unchanged")
	assert.Equal(t, []string{"finance"}, got.SuggestedTags, "the document's own tags are passed through unchanged")
	assert.Empty(t, got.SuggestedCorrespondent)
	assert.Empty(t, got.SuggestedDocumentType)
	assert.Empty(t, got.SuggestedCreatedDate)
	assert.Empty(t, got.SuggestedContent)
	assert.Empty(t, got.SuggestedCustomFields)
	assert.Empty(t, got.SuggestedSummary)
	assert.Contains(t, got.RemoveTags, autoTag)
}
